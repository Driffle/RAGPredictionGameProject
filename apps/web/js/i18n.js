  function geo() {
    return localStorage.getItem("floorbrief.geo") || "US";
  }

  function locale() {
    return GEO_LOCALE[geo()] || "en";
  }

  function dictionary() {
    return STRINGS[locale()] || STRINGS[locale().split("-")[0]] || STRINGS.en;
  }

  function t(key) {
    return dictionary()[key] || STRINGS.en[key] || key;
  }

  function format(key, params = {}) {
    return String(t(key)).replace(/\{(\w+)\}/g, (_, name) =>
      params[name] == null ? `{${name}}` : String(params[name])
    );
  }

  function apply() {
    document.documentElement.lang = locale();
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      node.placeholder = t(node.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAria));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.setAttribute("title", t(node.dataset.i18nTitle));
    });
    document.title = `${t("shell.title")} — ${t("shell.kicker")}`;
    const picker = document.querySelector("#geo-language");
    if (picker) {
      picker.innerHTML = MARKETS.map((row) => {
        const key = `market.${row.geo.toLowerCase()}`;
        const label = t(key);
        return `<option value="${row.geo}">${label}</option>`;
      }).join("");
      picker.value = geo();
    }
  }

  function setGeo(value) {
    if (!GEO_LOCALE[value]) return;
    localStorage.setItem("floorbrief.geo", value);
    window.location.reload();
  }

  window.FloorI18n = { t, format, apply, setGeo, geo, locale, STRINGS, MARKETS };
  document.addEventListener("DOMContentLoaded", apply);
